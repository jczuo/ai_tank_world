def get_level(level_idx):
    """获取关卡数据，循环使用"""
    return LEVELS[level_idx % len(LEVELS)]


def get_enemy_list(level_data):
    """将关卡敌人配置展开为列表"""
    enemies = []
    for etype, count in level_data["enemies"]:
        enemies.extend([etype] * count)
    import random
    random.shuffle(enemies)
    return enemies
